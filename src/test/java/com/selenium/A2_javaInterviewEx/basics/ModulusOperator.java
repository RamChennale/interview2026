package com.selenium.A2_javaInterviewEx.basics;

public class ModulusOperator {

    public static void main(String[] args){

/*
        Returns the division remainder
                */
        var a =11;
        var b =6;

        System.out.println(a%b);

        a =13;
        b =6;

        a++; //14
        b--; //5
        System.out.println(a%b); //14%5 - 4

    }

}
